-- Users who signed in through an OAuth provider.
CREATE TABLE app_user (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider          VARCHAR(20)  NOT NULL,
    provider_user_id  VARCHAR(100) NOT NULL,
    email             VARCHAR(320),
    display_name      VARCHAR(200),
    avatar_url        VARCHAR(1000),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_app_user_provider UNIQUE (provider, provider_user_id)
);

-- One row per (user, problem) that has any progress, flag or note.
CREATE TABLE problem_progress (
    user_id           BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    problem_slug      VARCHAR(120) NOT NULL,
    solved_at         TIMESTAMP WITH TIME ZONE,
    review_stage      INTEGER      NOT NULL DEFAULT 0,
    last_reviewed_at  TIMESTAMP WITH TIME ZONE,
    flagged           BOOLEAN      NOT NULL DEFAULT FALSE,
    note              VARCHAR(10000),
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_problem_progress PRIMARY KEY (user_id, problem_slug)
);

-- Spring Session (JDBC) tables, so logins survive server restarts.
CREATE TABLE spring_session (
    primary_id             CHAR(36)     NOT NULL,
    session_id             CHAR(36)     NOT NULL,
    creation_time          BIGINT       NOT NULL,
    last_access_time       BIGINT       NOT NULL,
    max_inactive_interval  INTEGER      NOT NULL,
    expiry_time            BIGINT       NOT NULL,
    principal_name         VARCHAR(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);

CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id  CHAR(36)     NOT NULL,
    attribute_name      VARCHAR(200) NOT NULL,
    attribute_bytes     BYTEA        NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);
