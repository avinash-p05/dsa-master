-- Email/password accounts (provider = 'local', provider_user_id = lower-cased email).
ALTER TABLE app_user ADD COLUMN password_hash VARCHAR(100);
ALTER TABLE app_user ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;

-- One-time tokens for email verification and password reset.
-- Only a SHA-256 hash of the token is stored; the raw token lives in the email link.
CREATE TABLE auth_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    purpose     VARCHAR(20) NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_auth_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_auth_token_user_purpose ON auth_token (user_id, purpose);
